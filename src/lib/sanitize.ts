/** Security utilities for input sanitization, validation, and rate limiting. */

/** Escape HTML special characters to prevent XSS when embedding in raw HTML. */
export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
